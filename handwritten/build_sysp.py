def main() -> int:
    rows = []
    seen = set()
    n = 0
    for chapter, sentences in TEXTS.items():
        for text in sentences:
            if text in seen:
                continue
            seen.add(text)
            n += 1
            rows.append({
                "id": f"sysp-{n}",
                "text": text,
                "source": "《二十四诗品》",
                "book": "二十四诗品",
                "chapter": chapter,
            })

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "sysp.json")
    with open(out, "w", encoding="utf-8") as fh:
        json.dump(rows, fh, ensure_ascii=False, indent=2)
    print(f"写入 {out}: {len(rows)} 条（{len(TEXTS)} 品）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
